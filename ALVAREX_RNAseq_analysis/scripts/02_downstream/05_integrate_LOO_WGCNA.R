## Helper TOM
load_tom_edges <- function(mod_col, tom_directory, quantile_thr) {
  candidates <- list.files(
    tom_directory,
    pattern    = paste0(mod_col, ".*edges.*TOM\\.csv|edges.*", mod_col, ".*TOM\\.csv"),
    full.names = TRUE
  )
  if (length(candidates) == 0) return(NULL)
  tom <- readr::read_csv(candidates[1], show_col_types = FALSE)
  if (!"weight" %in% colnames(tom)) {
    wt_col <- colnames(tom)[sapply(colnames(tom), function(x) is.numeric(tom[[x]]))]
    if (length(wt_col) == 0) return(NULL)
    tom <- dplyr::rename(tom, weight = dplyr::all_of(wt_col[1]))
  }
  if (!"source" %in% colnames(tom)) {
    if (all(c("fromNode","toNode") %in% colnames(tom)))
      tom <- dplyr::rename(tom, source = fromNode, target = toNode)
    else return(NULL)
  }
  thr <- quantile(tom$weight, probs = quantile_thr, na.rm = TRUE)
  tom <- dplyr::filter(tom, weight >= thr)
  tom$edge_type <- "co-expression_TOM"
  tom[, c("source","target","weight","edge_type")]
}

## Helper corrélation
compute_cor_edges <- function(genes, mat, threshold) {
  genes_avail <- intersect(genes, rownames(mat))
  if (length(genes_avail) < 2) return(NULL)
  cor_mat <- cor(t(mat[genes_avail, , drop = FALSE]),
                 use = "pairwise.complete.obs")
  idx <- which(upper.tri(cor_mat), arr.ind = TRUE)
  df <- data.frame(
    source    = rownames(cor_mat)[idx[,1]],
    target    = colnames(cor_mat)[idx[,2]],
    weight    = cor_mat[idx],
    edge_type = "co-expression_cor",
    stringsAsFactors = FALSE
  )
  dplyr::filter(df, abs(weight) >= threshold)
}

