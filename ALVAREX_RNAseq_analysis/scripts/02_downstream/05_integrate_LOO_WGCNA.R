## ── Calcul des composantes ──────────────────────────────────────────────────
tier1_counts <- integr_df |>
  dplyr::filter(!is.na(ModuleColor), ModuleColor != "grey") |>
  dplyr::group_by(ModuleColor) |>
  dplyr::summarise(
    N_genes      = dplyr::n(),
    N_Tier1_both = sum(Tier_Global == "Tier1_both",   na.rm = TRUE),
    N_Tier1_P    = sum(Tier_Global == "Tier1_P_only", na.rm = TRUE),
    N_Tier1_N    = sum(Tier_Global == "Tier1_N_only", na.rm = TRUE),
    N_Tier2      = sum(Tier_Global == "Tier2",        na.rm = TRUE),
    Pct_T1both   = round(100 * N_Tier1_both / dplyr::n(), 2),
    .groups = "drop"
  )

## Pré-calcul des maxima hors mutate (évite les problèmes de longueur)
tmp_base <- me_df |>
  dplyr::filter(!is.na(FDR), ModuleColor != "grey") |>
  dplyr::select(ME, ModuleColor, FDR) |>
  dplyr::left_join(tier1_counts, by = "ModuleColor") |>
  dplyr::mutate(
    raw_FDR = -log10(FDR),
    raw_Pct = Pct_T1both,
    raw_N   = as.numeric(N_Tier1_both)
  )

max_FDR <- max(tmp_base$raw_FDR, na.rm = TRUE)
max_Pct <- max(tmp_base$raw_Pct, na.rm = TRUE)
max_N   <- max(tmp_base$raw_N,   na.rm = TRUE)

composite_df <- tmp_base |>
  dplyr::mutate(
    ## Normalisation 0→1
    S_FDR = raw_FDR / max_FDR,
    S_Pct = raw_Pct / max_Pct,
    S_N   = raw_N   / max_N,
    
    ## Score composite (0–100)
    Score_composite = round(
      (SCORE_WEIGHTS$fdr * S_FDR +
         SCORE_WEIGHTS$pct * S_Pct +
         SCORE_WEIGHTS$n   * S_N) * 100,
      1
    ),
    
    ## Contributions individuelles
    C_FDR = round(SCORE_WEIGHTS$fdr * S_FDR * 100, 1),
    C_Pct = round(SCORE_WEIGHTS$pct * S_Pct * 100, 1),
    C_N   = round(SCORE_WEIGHTS$n   * S_N   * 100, 1),
    
    ## Catégories
    FDR_sig = dplyr::case_when(
      FDR < 0.001 ~ "***",
      FDR < 0.01  ~ "**",
      FDR < 0.05  ~ "*",
      FDR < 0.10  ~ ".",
      TRUE        ~ "ns"
    ),
    Priority = dplyr::case_when(
      Score_composite >= 50 ~ "Priorité 1",
      Score_composite >= 25 ~ "Priorité 2",
      Score_composite >= 10 ~ "Priorité 3",
      TRUE                  ~ "Faible"
    ),
    Priority = factor(Priority,
                      levels = c("Priorité 1","Priorité 2","Priorité 3","Faible"))
  ) |>
  dplyr::arrange(dplyr::desc(Score_composite))

