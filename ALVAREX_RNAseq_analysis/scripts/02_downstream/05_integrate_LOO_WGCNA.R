save_gg <- function(p, base_path, width = 8, height = 6, dpi = 600) {
  ggplot2::ggsave(paste0(base_path, ".pdf"), p, width = width, height = height, bg = "white")
  ggplot2::ggsave(paste0(base_path, ".png"), p, width = width, height = height,
                  dpi = dpi, bg = "white")
