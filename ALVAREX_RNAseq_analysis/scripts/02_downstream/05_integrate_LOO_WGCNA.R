## PARTIE 5B — SCORE COMPOSITE DE PRIORITÉ DES MODULES
## ══════════════════════════════════════════════════════════════════════════
##
## Formule (3 composantes, sans beta) :
##   Score = 0.45 × S_FDR + 0.40 × S_Pct_T1both + 0.15 × S_N_T1both
##
##   S_FDR  = -log10(FDR lmerTest)   → significativité statistique
##   S_Pct  = % Tier1_both du module → enrichissement en DEG robustes LOO
##   S_N    = N Tier1_both (absolu)  → poids biologique brut
##
##   Chaque composante est normalisée 0→1 (valeur / max de la série)
##   avant pondération, puis multipliée par 100.
## ══════════════════════════════════════════════════════════════════════════

SCORE_WEIGHTS <- list(
  fdr = 0.45,
  pct = 0.40,
  n   = 0.15
)

cat("════════════════════════════════════════\n")
cat("PARTIE 5B — Score composite modules\n")
