                dplyr::coalesce(mod_info$Pct_T1both[1], 0)))
  }
  
  ## ── Nœuds ──────────────────────────────────────────────────────────────
  nodes_raw <- integr_df |>
    dplyr::filter(ModuleColor == mod_col, !is.na(kME_own),
                  kME_own >= CYTO_KME_MIN) |>
    dplyr::arrange(dplyr::desc(kME_own)) |>
    dplyr::slice_head(n = CYTO_MAX_NODES) |>
    dplyr::distinct(Gene, .keep_all = TRUE)
  
  n_nodes <- nrow(nodes_raw)
  cat("  Nœuds (kME ≥", CYTO_KME_MIN, ") :", n_nodes, "\n")
  
  if (n_nodes < 3) {
    cat("  ⚠️  < 3 nœuds — module ignoré\n\n"); next
  }
  
  nodes_out <- nodes_raw |>
    dplyr::mutate(
      Tier      = as.character(dplyr::coalesce(as.character(Tier_Global), "NS")),
      NodeColor = dplyr::coalesce(TIER_HEX[Tier], "#BDBDBD"),
      NodeSize  = dplyr::case_when(
        kME_own >= 0.80 ~ 60,
        kME_own >= 0.60 ~ 40,
        TRUE            ~ 25
      ),
      NodeShape = dplyr::case_when(
        Status == "Up"   ~ "ELLIPSE",
        Status == "Down" ~ "RECTANGLE",
        TRUE             ~ "DIAMOND"
      ),
      ## Étiquette = Tier1_both ou hub (kME ≥ 0.80)
      NodeLabel = dplyr::if_else(
        Tier == "Tier1_both" | kME_own >= 0.80, Gene, ""
      ),
      Module_FDR_str = ifelse(is.na(Module_FDR), "NS",
                              formatC(Module_FDR, format="e", digits=2)),
      log2FC_str     = ifelse(is.na(log2FoldChange), "NA",
                              as.character(round(log2FoldChange, 3))),
      FDR_edgeR_str  = ifelse(is.na(padj), "NS",
                              formatC(padj, format="e", digits=2))
    ) |>
    dplyr::select(
      name      = Gene,
      Module    = ModuleColor,
      Tier, NodeColor, NodeSize, NodeShape, NodeLabel,
      kME       = kME_own,
      GS        = GS_Protection,
      log2FC    = log2FoldChange,
      FDR_edgeR = padj,
      Direction = Status,
      aveLogCPM, LOO_Score_P, LOO_Score_N,
      Module_FDR, Module_beta, Module_FDR_str, log2FC_str, FDR_edgeR_str
    )
  
  ## ── Arêtes ─────────────────────────────────────────────────────────────
  genes_mod  <- nodes_out$name
  edges_raw  <- if (edge_method_used == "tom") {
    load_tom_edges(mod_col, tom_dir, CYTO_TOM_QUANTILE)
  } else if (edge_method_used == "cor" && !is.null(expr_mat)) {
    compute_cor_edges(genes_mod, expr_mat, CYTO_COR_THRESHOLD)
  } else NULL
  
  ## Fallback kME-product
  if (is.null(edges_raw) || nrow(edges_raw) == 0) {
    cat("  → Fallback kME-product\n")
    kme_vals <- setNames(nodes_out$kME, nodes_out$name)
    pairs    <- utils::combn(genes_mod, 2)
    edges_raw <- data.frame(
      source    = pairs[1,],
      target    = pairs[2,],
      weight    = kme_vals[pairs[1,]] * kme_vals[pairs[2,]],
      edge_type = "kME_product",
      stringsAsFactors = FALSE
    )
    thr_kp    <- quantile(edges_raw$weight, 0.75, na.rm = TRUE)
    edges_raw <- dplyr::filter(edges_raw, weight >= thr_kp)
  }
  
  ## Filtrer aux nœuds retenus + cap absolu
  edges_out <- edges_raw |>
    dplyr::filter(source %in% genes_mod, target %in% genes_mod) |>
    dplyr::arrange(dplyr::desc(weight)) |>
    dplyr::slice_head(n = CYTO_MAX_EDGES)
  
  n_edges <- nrow(edges_out)
  cat("  Arêtes :", n_edges, "\n")
  cat("  Nœuds Tier1_both :", sum(nodes_out$Tier == "Tier1_both"),
      "| kME ≥ 0.80 :", sum(nodes_out$kME >= 0.80), "\n\n")
  
  ## Sauvegarder
  readr::write_csv(nodes_out,
                   file.path(dir_cyto, paste0("nodes_", mod_col, ".csv")))
  readr::write_csv(edges_out,
                   file.path(dir_cyto, paste0("edges_", mod_col, ".csv")))
  
  all_node_tables[[mod_col]] <- nodes_out
  all_edge_tables[[mod_col]] <- edges_out
}

